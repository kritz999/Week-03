package LinkedList.doublylinkedlist.moviemanagementsystem;

public class Movie {
    String title;
    String director;
    int yearOfRelease;
    double rating;

    public Movie(String title, String director, int yearOfRelease, double rating) {
        this.title = title;
        this.director = director;
        this.yearOfRelease = yearOfRelease;
        this.rating = rating;
    }
}
