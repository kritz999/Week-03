package LinkedList.singlylinkedlist.studentrecordmanagement;

public class StudentRecord {
    int rollNumber;
    String name;
    int age;
    char grade;

    // Constructor
    public StudentRecord(int rollNumber, String name, int age, char grade) {
        this.rollNumber = rollNumber;
        this.name = name;
        this.age = age;
        this.grade = grade;
    }
}
